module Schematrix
  module Generators
    # Base class for all output generators. A generator renders the
    # compiled record of one object schema as one file: an ERB template
    # filled through a template helper class, then formatted with
    # SyntaxTree. Subclasses provide the template and, optionally,
    # override helper methods to produce different output formats.
    #
    # The shared rendering lives in the Templates modules:
    # Templates::RubyHelpers (constructor, from_h/to_h),
    # Templates::Coercions (the coerce_ methods),
    # Templates::SorbetHelpers and Templates::TypeComposer (type
    # algebra for the Sorbet and RBS notations), and
    # Templates::Base (declaration scaffolding).
    class Base
      include Resolver

      # Ruby keywords that cannot appear as generated accessor names or
      # keyword arguments; property_name suffixes them with "_".
      RUBY_KEYWORDS = %w[
        BEGIN
        END
        alias
        and
        begin
        break
        case
        class
        def
        defined?
        do
        else
        elsif
        end
        ensure
        false
        for
        if
        in
        module
        next
        nil
        not
        or
        redo
        rescue
        retry
        return
        self
        super
        then
        true
        undef
        unless
        until
        when
        while
        yield
      ].freeze

      # Method names the immutable surface adds on top of the
      # property readers: the copier, the catch-all keyword and its
      # protected reader, and the digest half of the value equality.
      # A property folding onto one takes the keyword treatment, with
      # ORIGINAL_KEYS still recording it.
      IMMUTABLE_RESERVED_METHOD_NAMES = %w[with _extra hash].freeze

      # `output_dir` is the directory files are written to (created on
      # demand), `module_name` the namespace generated code is placed
      # in. `format: false` skips SyntaxTree formatting and emits the
      # template output as-is. `command` names the regenerating command
      # in the written files' banner; nil leaves that line out.
      # `scalar_types` maps [type, format] pairs to ScalarType
      # renderings of the project's own; it merges over
      # BUILTIN_SCALAR_TYPES. A coercer must be a named module
      # answering `coerce(value)`, since the generated code calls
      # `#{coercer.name}.coerce(value)`: anything else fails here, at
      # construction, before any file can be written.
      # `immutable: true` renders data classes as frozen value
      # objects: readers instead of accessors, a `with` copier, and
      # value equality. It applies to the data generators only; the
      # DSL builders refuse it.
      def initialize(
        output_dir,
        module_name,
        format: true,
        command: nil,
        scalar_types: {},
        immutable: false
      )
        assert_immutable_supported if immutable
        @output_dir = output_dir
        @module_name = module_name
        @format = format
        @command = command
        @scalar_types = Schematrix::BUILTIN_SCALAR_TYPES.merge(scalar_types)
        @immutable = immutable
        assert_coercers_valid(@scalar_types)
      end

      # Whether this generator's output honors the immutable option.
      # The data generators do; the DSL builders answer through
      # DslNaming.
      def self.immutable_supported? = true

      # The file this locator's class writes to, without writing it:
      # callers that batch many schemas check every target up front.
      def target_path(locator)
        class_name = class_name_from_path(URI(locator))
        File.join(@output_dir, target_filename(class_name))
      end

      # Renders, formats, and writes the file for this locator's
      # class, creating the output directory when missing. The file
      # carries the autogenerated banner. Returns the path written.
      def write(locator, object)
        uri = URI(locator)
        class_name = class_name_from_path(uri)
        code = with_banner(transform(uri, class_name, object), class_name)

        file_path = File.join(@output_dir, target_filename(class_name))
        FileUtils.mkdir_p(File.dirname(file_path))

        File.write(file_path, code)
        file_path
      end

      # Fills the ERB template through this generator's template class
      # and formats the result. Returns the file content.
      def transform(path, class_name, object)
        code = template(path, class_name, object).render(self.class.erb)

        format_code(code)
      end

      # The ERB object for this generator's template file, compiled
      # once per class.
      def self.erb
        @erb ||=
          begin
            template_file =
              File.join(File.dirname(__FILE__), "templates", template_name)
            ERB.new(File.read(template_file), trim_mode: "-")
          end
      end

      # Name of the template helper class that fills this generator's
      # ERB template.
      def self.template_class
        raise NotImplementedError, "#{name} must implement #template_class"
      end

      # Name of the ERB file under generators/templates this generator
      # renders through.
      def self.template_name
        raise NotImplementedError, "#{name} must implement #template_name"
      end

      # File extension of this generator's output, including the dot.
      def self.file_extension
        raise NotImplementedError, "#{name} must implement #file_extension"
      end

      private

      # The immutable option only reshapes data classes: a builder
      # accumulates a document, so it is mutable by construction, and
      # asking for an immutable one fails here, at construction,
      # before any file can be written.
      def assert_immutable_supported
        return if self.class.immutable_supported?

        raise ArgumentError,
              "#{self.class.name} generates mutable DSL builders; " \
                "immutable applies to data generators"
      end

      # Every coercer the merged table carries, checked whenever the
      # generator is built: a value without a coercer is fine, an
      # anonymous module or one without `coerce` cannot back the
      # emitted `name.coerce(value)` call.
      def assert_coercers_valid(table)
        table.each_value do |entry|
          coercer = entry.coercer
          next if coercer.nil? || callable_coercer?(coercer)

          raise ArgumentError,
                "scalar_types coercer #{coercer.inspect} must be a named " \
                  "module answering .coerce(value)"
        end
      end

      # Whether the generated `coercer.name.coerce(value)` call can
      # resolve: the name must exist and the method with it.
      def callable_coercer?(coercer)
        coercer.is_a?(Module) && !coercer.name.nil? &&
          coercer.respond_to?(:coerce)
      end

      # Prepends the autogenerated banner, after the Sorbet sigil when
      # the output carries one, at the top otherwise. Worded after
      # tapioca's generated-file header.
      def with_banner(code, class_name)
        lines = [
          "# DO NOT EDIT MANUALLY",
          "# This is an autogenerated file for the #{class_name} class.",
        ]
        if @command
          lines << "# Please instead update this file by running `#{@command}`."
        end

        header = lines.join("\n")
        if code.start_with?("# typed:")
          sigil_end = code.index("\n")
          "#{code[0..sigil_end]}\n#{header}\n#{code[(sigil_end + 1)..]}"
        else
          "#{header}\n\n#{code}"
        end
      end

      # Builds the template object the ERB renders through: mangled
      # property names, the original-key map, the catch-all schema,
      # and the description comment, alongside the module, path, and
      # class name. Mangled-name collisions are warned from here.
      def template(path, class_name, object)
        properties = object&.properties
        mangled_names = mangled_property_names(properties)
        property_keys =
          mangled_names.map { |original, name| [original, name.to_sym] }
        warn_mangled_collisions(class_name, path, property_keys)
        self.class.template_class.new(
          module_name: @module_name,
          path:,
          class_name: class_name,
          properties:
            properties&.transform_keys { |key| mangled_names.fetch(key) },
          property_keys:,
          additional_properties: object.additional_properties,
          documentation_comment: documentation_comment(object),
          scalar_types: @scalar_types,
          immutable: @immutable,
        )
      end

      # SyntaxTree formatting, skipped when the generator was built
      # with format: false.
      def format_code(code)
        return SyntaxTree.format(code) if @format

        code
      end

      # One comment line per description line: raw newlines inside a
      # description would leak the remaining lines as code.
      def documentation_comment(schema)
        description = schema.description
        return "" if description.nil?

        description.lines.map { |line| "# #{line.chomp}".rstrip }.join("\n")
      end

      # The file name for a resolved class name: snake-cased name plus
      # the generator's extension.
      def target_filename(class_name)
        "#{underscore(class_name)}#{self.class.file_extension}"
      end

      # A property name safe to use as a Ruby identifier: snake-cased,
      # the leading "$" of core vocabulary keywords ($id, $ref, ...)
      # stripped, characters identifiers cannot carry replaced with
      # underscores, a leading digit prefixed, and Ruby keywords
      # suffixed with an underscore so generated accessors and keyword
      # arguments stay parseable. A name with no representable
      # character folds to its UTF-8 hex instead of a pile of
      # underscores, so sibling names stay distinct and the class-name
      # derivation (which folds the same hex) agrees with the file
      # that declares the class. Original keys stay reachable through
      # the catch-all accessors.
      def property_name(key)
        name = underscore(key).delete_prefix("$")
        name = name.gsub(/[^a-z0-9_]/, "_")
        name = key.unpack1("H*") if name.empty? || name.match?(/\A_+\z/)
        name = "_#{name}" if name.match?(/\A\d/)
        name = "_" if name.empty?
        name = "#{name}_" if RUBY_KEYWORDS.include?(name)
        if @immutable && IMMUTABLE_RESERVED_METHOD_NAMES.include?(name)
          name = "#{name}_"
        end
        name
      end

      # Mangles every property key exactly once: original String name
      # to mangled name, the inverse of property_name ($id -> id,
      # if -> if_). The mangled properties hash and the ORIGINAL_KEYS
      # pairs both derive from this pass; generated classes carry the
      # pairs as the ORIGINAL_KEYS constant so round-tripping inverts
      # the mangling, and from_h uses it to tell known keys from
      # catch-all riders.
      def mangled_property_names(properties)
        return {} if properties.nil?

        properties.keys.to_h { |key| [key, property_name(key)] }
      end

      # Mangling is not injective: sibling property names can fold to
      # one accessor (foo-bar and foo_bar), where transform_keys keeps
      # the last declaration's schema while ORIGINAL_KEYS, from_h and
      # to_h keep the first original's key. The class still compiles,
      # so the collision warns with the kept key instead of staying
      # silent.
      def warn_mangled_collisions(class_name, path, property_keys)
        property_keys
          .group_by { |_original, mangled| mangled }
          .each do |mangled, pairs|
            next if pairs.size == 1

            originals = pairs.map(&:first)
            Schematrix.logger&.warn(
              "#{class_name}: properties #{originals.inspect} collapse " \
                "onto the accessor #{mangled}; from_h and to_h keep " \
                "#{originals.first.inspect} (#{path})",
            )
          end
      end
    end

    # Outputs a schema as a plain, mutable Ruby class, with no type
    # annotations.
    class PlainRuby < Base
      def self.template_name = "plain_ruby.erb"
      def self.file_extension = ".rb"
      def self.template_class = Templates::PlainRuby
    end

    # Outputs RBS type signatures matching a JSON Schema object.
    class Rbs < Base
      def self.template_name = "rbs.erb"
      def self.file_extension = ".rbs"
      def self.template_class = Templates::Rbs

      private

      # Formats with syntax_tree-rbs instead of plain SyntaxTree.
      def format_code(code) = @format ? SyntaxTree::RBS.format(code) : code
    end

    # Outputs a schema as a mutable Ruby class with inline Sorbet
    # signatures and real method bodies, under `# typed: strict`.
    class SorbetRuby < Base
      def self.template_name = "sorbet_ruby.erb"
      def self.file_extension = ".rb"
      def self.template_class = Templates::SorbetRuby
    end

    # Outputs a schema as an RBI Sorbet signature file: signatures
    # only, empty bodies.
    class Rbi < Base
      def self.template_name = "rbi.erb"
      def self.file_extension = ".rbi"
      def self.template_class = Templates::Rbi
    end

    # Naming overrides shared by the DSL generators: builder classes
    # nest under a Dsl module level, so the builder family and the
    # data-class family can never fold onto one constant or one
    # file, and the builder's own surface names stay reserved.
    module DslNaming
      # A property whose mangled name lands here would override the
      # generated entry point, the dump method, the catch-all
      # setter, or the constructor; it takes the keyword treatment
      # instead (a trailing underscore), with ORIGINAL_KEYS still
      # recording the mapping.
      RESERVED_METHOD_NAMES = %w[build to_h extra initialize].freeze

      def self.included(base)
        base.extend(ClassMethods)
      end

      # Builders accumulate a document, so no builder is immutable.
      module ClassMethods
        def immutable_supported? = false
      end

      def class_name_from_path(uri, name = nil)
        "Dsl::#{super}"
      end

      def property_name(key)
        name = super
        name = "#{name}_" if RESERVED_METHOD_NAMES.include?(name)
        name
      end
    end

    # Outputs the schema's DSL builders as plain, mutable Ruby
    # classes, with no type annotations.
    class DslPlainRuby < Base
      include DslNaming

      def self.template_name = "dsl_plain_ruby.erb"
      def self.file_extension = ".rb"
      def self.template_class = Templates::DslPlainRuby
    end

    # Outputs the DSL builders with inline Sorbet signatures and
    # real method bodies, under `# typed: strict`.
    class DslSorbetRuby < Base
      include DslNaming

      def self.template_name = "dsl_sorbet_ruby.erb"
      def self.file_extension = ".rb"
      def self.template_class = Templates::DslSorbetRuby
    end

    # Outputs the DSL builders as an RBI Sorbet signature file:
    # signatures only, empty bodies.
    class DslRbi < Base
      include DslNaming

      def self.template_name = "dsl_rbi.erb"
      def self.file_extension = ".rbi"
      def self.template_class = Templates::DslRbi
    end

    # Outputs the DSL builders as RBS signature files.
    class DslRbs < Base
      include DslNaming

      def self.template_name = "dsl_rbs.erb"
      def self.file_extension = ".rbs"
      def self.template_class = Templates::DslRbs

      private

      # Formats with syntax_tree-rbs instead of plain SyntaxTree.
      def format_code(code) = @format ? SyntaxTree::RBS.format(code) : code
    end
  end

  # The generator registry the CLI resolves `-g` names against:
  # `plain_ruby`, `rbs`, `sorbet_ruby`, `rbi`, and the dsl_ prefixed
  # builders of each.
  GENERATORS = {
    "plain_ruby" => Generators::PlainRuby,
    "rbs" => Generators::Rbs,
    "sorbet_ruby" => Generators::SorbetRuby,
    "rbi" => Generators::Rbi,
    "dsl_plain_ruby" => Generators::DslPlainRuby,
    "dsl_sorbet_ruby" => Generators::DslSorbetRuby,
    "dsl_rbi" => Generators::DslRbi,
    "dsl_rbs" => Generators::DslRbs,
  }.freeze
end
